def test_sigkill_mid_public_test_resumes_without_duplicate_provider_call(
    tmp_path: Path,
) -> None:
    if os.name != "posix":
        pytest.skip("SIGKILL restart coverage requires the Linux WSL runner")
    workspace, files, commit = _workspace(tmp_path, GO_BUGGY)
    snapshot = workspace.snapshot()
    job = _direct_job(snapshot, commit)
    ledger_root = tmp_path / "ledger"
    config_path = tmp_path / "crash.json"
    config = {
        "workspace": str(tmp_path / "crash-workspace"),
        "origin": str(tmp_path / "origin"),
        "repository": "golang/example",
        "commit": commit,
        "task_id": str(job.task_id),
        "finding_id": job.finding_id,
        "title": job.finding_title,
        "handoff": job.handoff.model_dump(mode="json"),
        "plan": _fix_plan(files).model_dump(mode="json"),
        "verification_files": VERIFICATION_FILES,
        "verification_tests": VERIFICATION_TESTS,
        "budget": job.budget.model_dump(mode="json"),
        "ledger": str(ledger_root),
        "allowed_actors": ["r03-owner"],
    }
    config_path.write_text(json.dumps(config), encoding="utf-8")
    environment = {
        **os.environ,
        "PYTHONPATH": str(ROOT / "src"),
        "PYTHONDONTWRITEBYTECODE": "1",
    }

    crashed = subprocess.run(
        [sys.executable, "-c", CRASH_SCRIPT, str(config_path)],
        cwd=ROOT,
        env=environment,
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert crashed.returncode != 0

    ledger = JsonRepairLedger(ledger_root)
    checkpoint = ledger.load(job.task_id, job.finding_id)
    assert checkpoint is not None
    assert checkpoint.phase in {"public_tests", "patching"}
    assert checkpoint.baseline is not None
    assert checkpoint.plans
    assert checkpoint.patches
    assert all(item.stage != "public_tests" for item in checkpoint.receipts)

    class _NoCallProvider:
        def propose(self, prompt: RepairPrompt) -> PatchPlan:
            raise AssertionError("a resumed repair must replay the recorded plan")

    resumed = AuthorizedRepairOrchestrator(
        ledger=ledger,
        allowed_actors=["r03-owner"],
        runtime=SnapshotRepairRuntime(),
    ).run(job, _NoCallProvider())

    assert resumed.status == "waiting_approval"
    assert resumed.review_bundle is not None
    final = ledger.load(job.task_id, job.finding_id)
    assert final is not None and final.phase == "waiting_approval"
    assert final.patches[0].patch_id == checkpoint.patches[0].patch_id
