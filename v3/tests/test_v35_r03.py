class _CancellingExecutor(SandboxExecutor):
    def __init__(self, token: RepairCancelToken, cancel_on: int = 2) -> None:
        super().__init__()
        self.token = token
        self.cancel_on = cancel_on
        self.calls = 0

    def run(
        self,
        files: Mapping[str, str],
        adapter: TestAdapter,
        *,
        timeout: float | None = None,
    ) -> tuple[TestReceipt, bytes]:
        self.calls += 1
        receipt, logs = super().run(files, adapter, timeout=timeout)
        if self.calls == self.cancel_on:
            self.token.cancel()
        return receipt, logs


def _direct_job(
    snapshot: RepositorySnapshot,
    commit: str,
    *,
    task_id: UUID | None = None,
    finding_id: str | None = None,
) -> AuthorizedRepairJob:
    handoff = _handoff(
        commit,
        approved_by="r03-owner",
        finding_id=finding_id or hashlib.sha256(b"r03-finding").hexdigest(),
    )
    return AuthorizedRepairJob(
        task_id=task_id or uuid4(),
        finding_id=handoff.finding_id,
        finding_title="weave autogenerated header is not its own line",
        finding_commit=commit,
        handoff=handoff,
        snapshot=snapshot,
        verification_files=VERIFICATION_FILES,
        verification_tests=VERIFICATION_TESTS,
        budget=RepairBudget(max_attempts=2, max_test_runs=9, deadline_seconds=300),
    )


def test_late_receipt_after_cancel_is_discarded_and_replay_is_inert(
    tmp_path: Path,
) -> None:
    workspace, files, commit = _workspace(tmp_path, GO_BUGGY)
    snapshot = workspace.snapshot()
    job = _direct_job(snapshot, commit)
    token = RepairCancelToken()
    ledger = JsonRepairLedger(tmp_path / "ledger")
    orchestrator = AuthorizedRepairOrchestrator(
        ledger=ledger,
        allowed_actors=["r03-owner"],
        runtime=SnapshotRepairRuntime(executor=_CancellingExecutor(token)),
    )
    provider = _Provider(_fix_plan(files))

    outcome = orchestrator.run(job, provider, cancel=token)

    assert outcome.status == "cancelled"
    assert outcome.review_bundle is None
    assert len(outcome.discarded_receipts) == 1
    assert outcome.discarded_receipts[0]["status"] == "passed"
    checkpoint = ledger.load(job.task_id, job.finding_id)
    assert checkpoint is not None and checkpoint.phase == "cancelled"
    assert all(item.stage != "public_tests" for item in checkpoint.receipts)

    replay_provider = _Provider()
    replayed = orchestrator.run(job, replay_provider, cancel=token)
    assert replayed.status == "cancelled"
    assert replay_provider.calls == 0


