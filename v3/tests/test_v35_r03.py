def _git(root: Path, *arguments: str) -> str:
    environment = {
        **os.environ,
        "GIT_AUTHOR_NAME": "R03 Fixture",
        "GIT_AUTHOR_EMAIL": "r03@example.invalid",
        "GIT_COMMITTER_NAME": "R03 Fixture",
        "GIT_COMMITTER_EMAIL": "r03@example.invalid",
        "GIT_AUTHOR_DATE": "2026-11-10T00:00:00Z",
        "GIT_COMMITTER_DATE": "2026-11-10T00:00:00Z",
        "GIT_CONFIG_NOSYSTEM": "1",
    }
    result = subprocess.run(
        ["git", *arguments],
        cwd=root,
        env=environment,
        capture_output=True,
        check=True,
        text=True,
    )
    return result.stdout.strip()


def _workspace(
    tmp_path: Path, source: Path, name: str = "workspace"
) -> tuple[RepositoryWorkspace, dict[str, str], str]:
    files = {
        "go.mod": "module example.invalid/weave\n\ngo 1.27\n",
        WEAVE: source.read_text(encoding="utf-8"),
        "internal/cmd/weave/weave_test.go": GO_PUBLIC_TEST,
    }
    origin = tmp_path / "origin"
    origin.mkdir(parents=True)
    for path, content in files.items():
        target = origin / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    _git(origin, "init", "-q", "-b", "main")
    _git(origin, "add", "-A")
    _git(origin, "-c", "commit.gpgsign=false", "commit", "-q", "-m", "fixed snapshot")
    commit = _git(origin, "rev-parse", "HEAD")
    workspace = RepositoryWorkspace(
        tmp_path / name,
        repository="golang/example",
        commit=commit,
        remote=str(origin),
        run_id="r03-test",
    )
    workspace.prepare()
    return workspace, files, commit


def _handoff(
    commit: str,
    *,
    approved_by: str,
    finding_id: str = "d" * 64,
    allow_repair: bool = True,
) -> RepairHandoff:
    repository = "golang/example"
    authorization = RepairAuthorization(
        approved_by=approved_by,
        expires_at=datetime.now(UTC) + timedelta(hours=1),
        allowed_repositories=[repository],
        limits=AnalysisLimits(),
        allow_repair=allow_repair,
    )
    evidence = FindingEvidence(
        evidence_id=str(uuid4()),
        kind="investigation",
        source_uri=f"https://github.com/{repository}/blob/{commit}/{WEAVE}",
        description="R03 fixed public repository snapshot investigation",
        content_hash="b" * 64,
    )
    proof = ReproductionProof(
        kind="reproduced",
        commit=commit,
        evidence_ids=[evidence.evidence_id],
        receipt_id="c" * 64,
        reproduce_command="trusted adapter: go test ./...",
    )
    draft = RepairHandoff(
        handoff_id="0" * 64,
        repository=repository,
        base_commit=commit,
        finding_id=finding_id,
        parent_run_id=uuid4(),
        parent_report_hash="e" * 64,
        evidence=[evidence],
        reproduction=proof,
        objective="Restore the fixed-commit autogenerated header inside the sandbox",
        allowed_paths=[WEAVE],
        execution_budget=AnalysisLimits(),
        authorization=authorization,
        authorization_hash=authorization.authorization_hash,
        execution_mode="live",
        finding_lifecycle="reproduced",
    )
    return draft.model_copy(update={"handoff_id": draft.computed_id()})


class _Provider:
    def __init__(
        self,
        plan: PatchPlan | None = None,
        rejection: PatchProposalRejected | None = None,
    ) -> None:
        self.plan = plan
        self.rejection = rejection
        self.calls = 0
        self.prompts: list[RepairPrompt] = []

    def propose(self, prompt: RepairPrompt) -> PatchPlan:
        self.calls += 1
        self.prompts.append(prompt)
        if self.rejection is not None:
            raise self.rejection
        if self.plan is None:
            raise AssertionError("the provider must not be called")
        return self.plan


def _fix_plan(files: dict[str, str]) -> PatchPlan:
    return PatchPlan(
        summary="Terminate the autogenerated header with a newline",
        edits=[
            FileEdit(
                path=WEAVE,
                operation="update",
                expected_sha256=sha256_text(files[WEAVE]),
                content=GO_FIXED.read_text(encoding="utf-8"),
            )
        ],
    )


def _shortcut_plan(files: dict[str, str]) -> PatchPlan:
    return PatchPlan(
        summary="Print only the public header",
        edits=[
            FileEdit(
                path=WEAVE,
                operation="update",
                expected_sha256=sha256_text(files[WEAVE]),
                content=SHORTCUT,
            )
        ],
    )


def _comment_plan(files: dict[str, str]) -> PatchPlan:
    return PatchPlan(
        summary="Leave the defect in place but change a comment",
        edits=[
            FileEdit(
                path=WEAVE,
                operation="update",
                expected_sha256=sha256_text(files[WEAVE]),
                content=files[WEAVE] + "\n// attempt without a behavior change\n",
            )
        ],
    )


def _task_and_finding(
    service: WorkbenchService,
    files: dict[str, str],
    commit: str,
) -> tuple[UUID, WorkbenchFinding]:
    request = CreateWorkbenchTask(
        repository_url="https://github.com/golang/example",
        mode="audit_and_repair",
        task="Repair the weave autogenerated header",
        execution_mode="live",
        auto_start=False,
        commit=commit,
    )
    task = service.store.create_task(
        request,
        repository="golang/example",
        commit=commit,
        request_key=f"r03:{uuid4()}",
        request_digest=digest(request.model_dump(mode="json")),
        task_text=request.task,
        limits=AnalysisLimits().model_dump(mode="json"),
    )
    finding = WorkbenchFinding(
        finding_id=hashlib.sha256(f"r03:{commit}:{WEAVE}".encode()).hexdigest(),
        task_id=task["task_id"],
        title="weave autogenerated header is not its own line",
        summary="The autogenerated header is emitted on the same line as the heading.",
        path=WEAVE,
        source=FindingSource(
            kind="file",
            uri=f"github://golang/example@{commit}/{WEAVE}",
            evidence_id=str(uuid4()),
            quote="<!-- Autogenerated by weave; DO NOT EDIT -->",
            content_hash=sha256_text(files[WEAVE]),
            commit=commit,
        ),
        reproduction_plan=ReproductionPlan(
            test_file="internal/cmd/weave/weave_test.go",
            test_node="TestGeneratedHeaderIsItsOwnLine",
            expected_failure="the header is not terminated by a newline",
        ),
        confidence=0.9,
    )
    service.store.upsert_findings(task["task_id"], [finding])
    return task["task_id"], finding


def test_authorized_repair_reaches_waiting_approval_with_real_sandbox(
    tmp_path: Path, settings: Settings, engine: Engine
) -> None:
    service = WorkbenchService(engine, settings)
    workspace, files, commit = _workspace(tmp_path, GO_BUGGY)
    snapshot = workspace.snapshot()
    task_id, finding = _task_and_finding(service, files, commit)
    handoff = _handoff(
        commit,
        approved_by=settings.allowed_actors[0],
        finding_id=finding.finding_id,
    )
    provider = _Provider(_fix_plan(files))

    result = service.authorized_repair(
        task_id,
        finding.finding_id,
        handoff=handoff,
        snapshot=snapshot,
        provider=provider,
        verification_files=VERIFICATION_FILES,
        verification_tests=VERIFICATION_TESTS,
        budget=RepairBudget(max_attempts=2, max_test_runs=9, deadline_seconds=300),
    )
    outcome = result["outcome"]

    assert outcome["status"] == "waiting_approval"
    assert outcome["test_runs"] >= 3
    assert outcome["budget"]["max_attempts"] == 2
    assert len(outcome["attempts"]) == 1
    assert outcome["attempts"][0]["accepted"] is True
    assert outcome["attempts"][0]["patch_id"]
    assert outcome["attempts"][0]["artifact_hash"]
    assert outcome["baseline"]["status"] == "test_failed"
    assert outcome["baseline"]["receipt"]["policy"]["network"] == "none"
    assert outcome["proposal"]["plan_summary"].startswith("Terminate")
    assert outcome["bundle_artifact"] is not None
    assert len(outcome["bundle_artifact"]) == 64
    assert provider.calls == 1
    assert all(
        "TestHiddenAutogeneratedBlockIsNewlineTerminated" not in json.dumps(item.model_dump())
        for item in provider.prompts
    )
    assert all(
        "hidden_test" not in path for prompt in provider.prompts for path in prompt.files
    )

    task = service.store.task(task_id)
    assert task["phase"] == "waiting_approval"
    assert task["status"] == "waiting_approval"
    stored = service.store.finding(task_id, finding.finding_id)
    assert stored.stage == "waiting_approval"
    assert stored.fix is not None and stored.fix.verified
    assert stored.approval is not None and stored.approval.status == "pending"
    assert stored.approval.payload_hash == stored.fix.bundle.payload_hash
    bundle_bytes = service.store.engine.artifacts.read(outcome["bundle_artifact"])
    assert stored.fix.bundle.proposal_id.encode() in bundle_bytes

    events = service.store.events(task_id)
    kinds = [event["kind"] for event in events]
    assert "repair.checkpoint" in kinds
    assert "repair.outcome" in kinds
    checkpoints = [
        event["payload"]["checkpoint"]
        for event in events
        if event["kind"] == "repair.checkpoint"
    ]
    assert any(item["patches"] for item in checkpoints)
    assert any(item["receipts"] for item in checkpoints)
    assert checkpoints[-1]["phase"] == "waiting_approval"


