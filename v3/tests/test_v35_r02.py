def test_handoff_worktree_rebuilds_the_fixed_snapshot_tree(tmp_path: Path) -> None:
    files = _go_files(GO_BUGGY)
    workspace, commit = _workspace(tmp_path, files, "golang/example")
    snapshot = workspace.snapshot()
    handoff = _handoff("golang/example", commit, ["internal/cmd/weave/weave.go"])

    with PatchWorktree.from_snapshot(handoff, snapshot) as worktree:
        assert worktree.tree_hash() == snapshot.tree
        assert worktree.snapshot()["internal/cmd/weave/weave.go"] == files[
            "internal/cmd/weave/weave.go"
        ]


