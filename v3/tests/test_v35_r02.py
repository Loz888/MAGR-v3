def test_repository_snapshot_binds_commit_tree_and_every_file_hash(tmp_path: Path) -> None:
    files = _go_files(GO_BUGGY)
    workspace, commit = _workspace(tmp_path, files, "golang/example")

    snapshot = workspace.snapshot()

    assert snapshot.repository == "golang/example"
    assert snapshot.commit == commit
    assert snapshot.binary_paths == []
    assert snapshot.file_sha256["internal/cmd/weave/weave.go"] == sha256_text(
        files["internal/cmd/weave/weave.go"]
    )
    assert tree(snapshot.files) == snapshot.tree
    assert snapshot.computed_hash() == snapshot.snapshot_hash
    assert snapshot.manifest_hash


def test_snapshot_refuses_bytes_tampered_after_materialization(tmp_path: Path) -> None:
    workspace, _ = _workspace(tmp_path, _go_files(GO_BUGGY), "golang/example")
    target = workspace.worktree / "internal/cmd/weave/weave.go"
    target.write_text(target.read_text(encoding="utf-8") + "\n// tampered\n", encoding="utf-8")

    with pytest.raises(DomainError) as caught:
        workspace.snapshot()

    assert caught.value.code == "WORKSPACE_FILE_MISMATCH"


