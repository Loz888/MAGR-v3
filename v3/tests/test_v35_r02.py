def _git(root: Path, *arguments: str) -> str:
    environment = {
        **os.environ,
        "GIT_AUTHOR_NAME": "R02 Fixture",
        "GIT_AUTHOR_EMAIL": "r02@example.invalid",
        "GIT_COMMITTER_NAME": "R02 Fixture",
        "GIT_COMMITTER_EMAIL": "r02@example.invalid",
        "GIT_AUTHOR_DATE": "2026-11-10T00:00:00Z",
        "GIT_COMMITTER_DATE": "2026-11-10T00:00:00Z",
        "GIT_CONFIG_NOSYSTEM": "1",
    }
    result = subprocess.run(
        ["git", *arguments],
        cwd=root,
        env=environment,
        capture_output=True,
        check=True,
        text=True,
    )
    return result.stdout.strip()


def _repository(tmp_path: Path, files: dict[str, str]) -> tuple[Path, str]:
    origin = tmp_path / "origin"
    origin.mkdir(parents=True)
    for name, content in files.items():
        target = origin / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    _git(origin, "init", "-q", "-b", "main")
    _git(origin, "add", "-A")
    _git(origin, "-c", "commit.gpgsign=false", "commit", "-q", "-m", "fixed snapshot")
    return origin, _git(origin, "rev-parse", "HEAD")


def _workspace(
    tmp_path: Path, files: dict[str, str], repository: str
) -> tuple[RepositoryWorkspace, str]:
    origin, commit = _repository(tmp_path, files)
    workspace = RepositoryWorkspace(
        tmp_path / "workspace",
        repository=repository,
        commit=commit,
        remote=str(origin),
        run_id="r02-test",
    )
    workspace.prepare()
    return workspace, commit


def _handoff(repository: str, commit: str, allowed_paths: list[str]) -> RepairHandoff:
    authorization = RepairAuthorization(
        approved_by="r02-owner",
        expires_at=datetime.now(UTC) + timedelta(hours=1),
        allowed_repositories=[repository],
        limits=AnalysisLimits(),
        allow_repair=True,
    )
    evidence = FindingEvidence(
        evidence_id=str(uuid4()),
        kind="investigation",
        source_uri=f"https://github.com/{repository}/blob/{commit}/{allowed_paths[0]}",
        description="R02 fixed public repository snapshot reproduction",
        content_hash="b" * 64,
    )
    proof = ReproductionProof(
        kind="reproduced",
        commit=commit,
        evidence_ids=[evidence.evidence_id],
        receipt_id="c" * 64,
        reproduce_command="trusted adapter: go test ./... / python runner.py",
    )
    draft = RepairHandoff(
        handoff_id="0" * 64,
        repository=repository,
        base_commit=commit,
        finding_id="d" * 64,
        parent_run_id=uuid4(),
        parent_report_hash="e" * 64,
        evidence=[evidence],
        reproduction=proof,
        objective="Restore the fixed-commit behavior inside the R03 sandbox",
        allowed_paths=allowed_paths,
        execution_budget=AnalysisLimits(),
        authorization=authorization,
        authorization_hash=authorization.authorization_hash,
        execution_mode="live",
        finding_lifecycle="reproduced",
    )
    return draft.model_copy(update={"handoff_id": draft.computed_id()})


class _Provider:
    def __init__(self, plan: PatchPlan | None = None) -> None:
        self.plan = plan
        self.calls = 0

    def propose(self, prompt: RepairPrompt) -> PatchPlan:
        self.calls += 1
        if self.plan is None:
            raise AssertionError("the provider must not be called")
        return self.plan


