def test_stale_sandbox_containers_are_reclaimed_by_owner_label() -> None:
    executor = SandboxExecutor()
    lock = executor.lock()
    name = f"mgar-v3-r02-orphan-{uuid4().hex[:10]}"
    created = subprocess.run(
        [
            "docker",
            "create",
            "--name",
            name,
            "--label",
            "mgar.v3.r03.sandbox=orphan-r02",
            "--network=none",
            lock["image_id"],
            "/bin/true",
        ],
        capture_output=True,
        check=False,
    )
    assert created.returncode == 0, created.stderr.decode()
    try:
        assert executor.reclaim_stale() >= 1
        remaining = subprocess.run(
            ["docker", "ps", "-aq", "--filter", f"name={name}"],
            capture_output=True,
            check=True,
        )
        assert remaining.stdout.decode().strip() == ""
    finally:
        subprocess.run(["docker", "rm", "-f", name], capture_output=True, check=False)


